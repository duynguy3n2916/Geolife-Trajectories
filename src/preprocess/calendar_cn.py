def in_china(lat: float, lon: float) -> bool:
    """Hộp thô quanh Trung Quốc đại lục (bao cả vài vùng lân cận; GeoLife chủ yếu ở Bắc Kinh)."""
    return 18.0 <= lat <= 54.0 and 73.0 <= lon <= 135.0


def is_workday_cn(day) -> bool:
    day = np.datetime64(day, "D")
    if day in HOLIDAYS:
        return False
    if day in MAKEUP:
        return True
    return (day.astype(int) + 4) % 7 < 5      # 1970-01-01 là thứ Năm
